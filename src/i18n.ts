export function initialLocale(): Locale {
  const saved = localStorage.getItem("ipeenv:locale");
  if (saved === "pt-BR" || saved === "en-US") {
    return saved;
  }
  return navigator.language.toLowerCase().startsWith("en") ? "en-US" : "pt-BR";
}

export function translate(
  locale: Locale,
  key: string,
  params: Record<string, string | number> = {},
) {
  const source = locale === "pt-BR" ? ptBR : enUS;
  const template = source[key] ?? translateDynamic(locale, key);
  return Object.entries(params).reduce(
    (text, [name, value]) => text.split(`{{${name}}}`).join(String(value)),
    template,
  );
}

function translateDynamic(locale: Locale, key: string) {
  if (locale === "en-US" && key.startsWith("Verificando PHP ")) {
    return `Checking PHP ${key.replace("Verificando PHP ", "")}`;
  }
  return key;
}
